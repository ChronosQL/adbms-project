// Rich location dictionary with PostGIS coordinates (WGS84 / EPSG:4326)
// and categories. Each location is formatted as an object with full backwards
// compatibility helpers (toString, toLowerCase, includes).

function loc(label, category, lat, lng) {
  return {
    label,
    category,
    lat,
    lng,
    toLowerCase() { return label.toLowerCase(); },
    toString() { return label; },
    includes(s) { return label.toLowerCase().includes(String(s).toLowerCase()); },
  };
}

